import PDFDocument from "pdfkit";
import type { computeReportCard } from "./exam.service";

type ReportCard = Awaited<ReturnType<typeof computeReportCard>>;

/**
 * Real server-side report-card PDF (§19/§26-style document generation),
 * rendered with pdfkit from the exact same computed data as the JSON
 * report-card endpoint — so the PDF can never disagree with the API.
 * Access control happens in the route/service before this is called.
 */
export function renderReportCardPdf(card: ReportCard): InstanceType<typeof PDFDocument> {
  const doc = new PDFDocument({ size: "A4", margin: 48 });
  const student = card.student as { admissionNumber?: string; firstName?: string; lastName?: string } | null;
  const cls = card.enrollment.class as { name?: string } | string;
  const sec = card.enrollment.section as { name?: string } | string;
  const className = typeof cls === "object" && cls ? cls.name ?? "" : "";
  const sectionName = typeof sec === "object" && sec ? sec.name ?? "" : "";

  doc.fontSize(20).fillColor("#111827").text("School ERP", { align: "center" });
  doc.fontSize(13).fillColor("#2563EB").text("Report Card", { align: "center" });
  doc.moveDown(0.4);
  doc.fontSize(11).fillColor("#111827").text(`${card.exam.name} (${card.exam.type})`, { align: "center" });
  doc.moveDown(1);

  doc.fontSize(11).text(`Student: ${student?.firstName ?? ""} ${student?.lastName ?? ""}`);
  doc.text(`Admission No: ${student?.admissionNumber ?? ""}`);
  doc.text(`Class: ${className}${sectionName ? ` — Section ${sectionName}` : ""}`);
  doc.moveDown(1);

  // Table header
  const left = 48; const marksX = 360; const maxX = 450;
  doc.fontSize(11).fillColor("#111827").text("Subject", left, doc.y, { continued: true });
  doc.text("Marks", marksX, doc.y, { continued: false });
  const headerY = doc.y;
  doc.text("Max", maxX, headerY - 14);
  doc.moveTo(left, doc.y + 2).lineTo(547, doc.y + 2).strokeColor("#2563EB").stroke();
  doc.moveDown(0.5);
  for (const s of card.subjects) {
    const subject = s.subject as { name?: string; code?: string } | null;
    const y = doc.y;
    doc.fontSize(10.5).fillColor("#111827").text(`${subject?.name ?? ""}${subject?.code ? ` (${subject.code})` : ""}`, left, y);
    doc.text(s.obtainedMarks === null ? "—" : String(s.obtainedMarks), marksX, y);
    doc.text(String(s.maxMarks), maxX, y);
    doc.moveDown(0.6);
  }
  doc.moveTo(left, doc.y + 2).lineTo(547, doc.y + 2).strokeColor("#94A3B8").stroke();
  doc.moveDown(0.8);

  doc.fontSize(11.5).text(`Total: ${card.totalObtained} / ${card.totalMax}`);
  doc.text(`Percentage: ${card.percentage}%`);
  if (card.grade) doc.text(`Grade: ${card.grade}${card.gradeRemark ? ` — ${card.gradeRemark}` : ""}`);
  if (card.position !== null && card.position !== undefined) doc.text(`Class Position: ${card.position}`);
  doc.moveDown(1.5);
  doc.fontSize(9).fillColor("#64748B").text(`Generated by School ERP on ${new Date().toLocaleDateString()}. This report card is generated from published results only.`, { align: "center" });
  doc.end();
  return doc;
}
