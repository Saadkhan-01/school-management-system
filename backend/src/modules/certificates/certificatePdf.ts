
import PDFDocument from "pdfkit";
/** Certificate PDF (§26) — same pdfkit pattern as the Phase 5 report card / Phase 7 documents: rendered server-side from the stored record, behind the same scope checks as the JSON endpoint. */
export function renderCertificatePdf(cert: { referenceNumber: string; type: string; issueDate: Date | string; status: string; student?: unknown }): InstanceType<typeof PDFDocument> {
  const doc = new PDFDocument({ size: "A4", margin: 56 });
  const st = cert.student as { firstName?: string; lastName?: string; admissionNumber?: string } | null;
  const name = st ? `${st.firstName ?? ""} ${st.lastName ?? ""}`.trim() : "";
  doc.fontSize(20).fillColor("#111827").text("School ERP", { align: "center" });
  doc.fontSize(15).fillColor("#2563EB").text(`${cert.type.replace(/-/g, " ").toUpperCase()} CERTIFICATE`, { align: "center" });
  doc.moveDown(1.5);
  doc.fontSize(12).fillColor("#111827").text(`This is to certify that ${name}${st?.admissionNumber ? ` (Admission No: ${st.admissionNumber})` : ""} is/was a student of this school.`, { align: "center" });
  doc.moveDown(2);
  doc.fontSize(11).text(`Reference: ${cert.referenceNumber}`);
  doc.text(`Type: ${cert.type}`);
  doc.text(`Issue date: ${new Date(cert.issueDate).toLocaleDateString()}`);
  doc.text(`Status: ${cert.status}`);
  doc.moveDown(2);
  doc.fontSize(9).fillColor("#64748B").text(`Verify this certificate at GET /api/v1/certificates/verify/${cert.referenceNumber}. Generated by School ERP.`, { align: "center" });
  doc.end(); return doc;
}
