import PDFDocument from "pdfkit";

/**
 * Payslip PDF (§13) — pdfkit, from the stored PayrollRun snapshot (the run
 * freezes the structure's figures at generation time, so a later salary
 * edit never rewrites an issued payslip). Access is checked in the service
 * before this renders: employees receive only their own payslip.
 * Amounts print as major units with 2 decimals; storage is integer minor units.
 */
type Row = Record<string, unknown>;
const fmt = (minor: unknown) => (Number(minor ?? 0) / 100).toFixed(2);
const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

export function renderPayslipPdf(run: Row): InstanceType<typeof PDFDocument> {
  const doc = new PDFDocument({ size: "A4", margin: 48 });
  const monthName = MONTHS[(Number(run.month) - 1 + 12) % 12] ?? String(run.month);
  doc.fontSize(20).fillColor("#111827").text("School ERP", { align: "center" });
  doc.fontSize(13).fillColor("#2563EB").text("Payslip", { align: "center" });
  doc.moveDown(0.6);
  doc.fontSize(11).fillColor("#111827");
  doc.text(`Employee: ${String(run.employeeName ?? "")}`);
  if (run.employeeIdLabel) doc.text(`Employee ID: ${String(run.employeeIdLabel)}`);
  doc.text(`Period: ${monthName} ${String(run.year ?? "")}`);
  doc.text(`Status: ${String(run.status ?? "")}${run.status === "paid" && run.paidAt ? ` — paid on ${new Date(String(run.paidAt)).toLocaleDateString()}` : ""}`);
  doc.moveDown(1);
  doc.fontSize(11.5).text(`Base Salary: ${fmt(run.baseSalary)}`);
  doc.moveDown(0.4);
  doc.fontSize(11).text("Allowances:");
  const allowances = (run.allowances as Row[]) ?? [];
  if (allowances.length === 0) doc.fontSize(10.5).text("  — none —");
  for (const a of allowances) doc.fontSize(10.5).text(`  ${String(a.label ?? "")}: ${fmt(a.amount)}`);
  doc.fontSize(11).text(`Allowances Total: ${fmt(run.allowancesTotal)}`);
  doc.moveDown(0.4);
  doc.text("Deductions:");
  const deductions = (run.deductions as Row[]) ?? [];
  if (deductions.length === 0) doc.fontSize(10.5).text("  — none —");
  for (const d of deductions) doc.fontSize(10.5).text(`  ${String(d.label ?? "")}: ${fmt(d.amount)}`);
  doc.fontSize(11).text(`Deductions Total: ${fmt(run.deductionsTotal)}`);
  doc.moveDown(0.6);
  doc.moveTo(48, doc.y).lineTo(547, doc.y).strokeColor("#2563EB").stroke();
  doc.moveDown(0.5);
  doc.fontSize(11.5).text(`Gross: ${fmt(run.gross)}`);
  doc.fontSize(12.5).text(`Net Pay: ${fmt(run.net)}`);
  doc.moveDown(1.5);
  doc.fontSize(9).fillColor("#64748B").text("Generated by School ERP from the payroll run record. Salary information is confidential.", { align: "center" });
  doc.end();
  return doc;
}
