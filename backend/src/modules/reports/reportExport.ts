import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";
import type { ReportResult } from "./reports9.service";

/**
 * Shared report exporter (§27: PDF / Excel / CSV export) — Phase 9.
 * Renders ANY report in the registry from its flat `columns` + `rows`, so a
 * report can never be exportable with different data (or weaker access) than
 * its JSON form: the routes run the exact same runReport() first, then hand
 * the result here.
 *  - CSV: generated natively (RFC-4180 quoting).
 *  - XLSX: exceljs workbook (title + summary sheet header, typed cells).
 *  - PDF: pdfkit tabular layout with the Phase 5/7 document styling.
 */
export type ExportFormat = "csv" | "xlsx" | "pdf";
export const EXPORT_FORMATS: ExportFormat[] = ["csv", "xlsx", "pdf"];
export const EXPORT_CONTENT_TYPES: Record<ExportFormat, string> = {
  csv: "text/csv; charset=utf-8",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  pdf: "application/pdf",
};

function cellText(v: unknown): string {
  if (v === null || v === undefined) return "";
  if (v instanceof Date) return v.toISOString();
  if (typeof v === "object") return JSON.stringify(v);
  return String(v);
}
function csvEscape(s: string): string {
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function renderCsv(report: ReportResult): Buffer {
  const lines: string[] = [];
  lines.push([`# ${report.title}`, `generated ${report.generatedAt}`].map(csvEscape).join(","));
  for (const [k, v] of Object.entries(report.summary)) lines.push([`# summary: ${k}`, cellText(v)].map(csvEscape).join(","));
  lines.push(report.columns.map((c) => csvEscape(c.label)).join(","));
  for (const row of report.rows) lines.push(report.columns.map((c) => csvEscape(cellText(row[c.key]))).join(","));
  return Buffer.from(lines.join("\r\n") + "\r\n", "utf8");
}

export async function renderXlsx(report: ReportResult): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "School ERP";
  wb.created = new Date(report.generatedAt);
  const ws = wb.addWorksheet(report.key.slice(0, 31));
  ws.addRow([report.title]);
  ws.getRow(1).font = { bold: true, size: 14 };
  ws.addRow([`Generated: ${report.generatedAt}`]);
  for (const [k, v] of Object.entries(report.summary)) ws.addRow([`Summary — ${k}`, cellText(v)]);
  ws.addRow([]);
  const header = ws.addRow(report.columns.map((c) => c.label));
  header.font = { bold: true };
  for (const row of report.rows) {
    ws.addRow(report.columns.map((c) => {
      const v = row[c.key];
      return typeof v === "number" ? v : cellText(v);
    }));
  }
  report.columns.forEach((c, i) => { ws.getColumn(i + 1).width = Math.max(14, c.label.length + 4); });
  const buf = await wb.xlsx.writeBuffer();
  return Buffer.from(buf as ArrayBuffer);
}

export function renderPdf(report: ReportResult): InstanceType<typeof PDFDocument> {
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 40 });
  doc.fontSize(18).fillColor("#111827").text("School ERP", { align: "center" });
  doc.fontSize(13).fillColor("#2563EB").text(report.title, { align: "center" });
  doc.fontSize(9).fillColor("#64748B").text(`Generated ${report.generatedAt} · ${report.rows.length} row(s)`, { align: "center" });
  doc.moveDown(0.8);
  const summaryText = Object.entries(report.summary).map(([k, v]) => `${k}: ${cellText(v)}`).join("   ·   ");
  if (summaryText) { doc.fontSize(9.5).fillColor("#111827").text(summaryText); doc.moveDown(0.6); }
  if (report.note) { doc.fontSize(9).fillColor("#64748B").text(report.note); doc.moveDown(0.6); }

  const left = 40;
  const usable = 842 - 80; // A4 landscape width minus margins
  const colW = Math.max(60, Math.floor(usable / Math.max(1, report.columns.length)));
  const drawHeader = () => {
    const y = doc.y;
    report.columns.forEach((c, i) => doc.fontSize(9.5).fillColor("#111827").text(c.label, left + i * colW, y, { width: colW - 4, ellipsis: true }));
    doc.moveDown(0.4);
    doc.moveTo(left, doc.y).lineTo(left + usable, doc.y).strokeColor("#2563EB").stroke();
    doc.moveDown(0.3);
  };
  drawHeader();
  for (const row of report.rows) {
    if (doc.y > 520) { doc.addPage(); drawHeader(); }
    const y = doc.y;
    report.columns.forEach((c, i) => doc.fontSize(9).fillColor("#111827").text(cellText(row[c.key]), left + i * colW, y, { width: colW - 4, ellipsis: true }));
    doc.moveDown(0.55);
  }
  if (!report.rows.length) doc.fontSize(10).fillColor("#64748B").text("No records matched the selected filters.");
  doc.moveDown(1.2);
  doc.fontSize(8.5).fillColor("#64748B").text("Generated by School ERP from live records. Amounts suffixed (minor) are integer minor units.", { align: "center" });
  doc.end();
  return doc;
}

export async function renderExport(report: ReportResult, format: ExportFormat): Promise<Buffer | InstanceType<typeof PDFDocument>> {
  if (format === "csv") return renderCsv(report);
  if (format === "xlsx") return renderXlsx(report);
  return renderPdf(report);
}
